let currentLanguage: Language = getLanguage();

export function getCurrentLanguage(): Language {
  return currentLanguage;
}

export function getLanguage(): Language {
  if (typeof localStorage === "undefined") return "zh-CN";
  return localStorage.getItem("gitkit.language") === "en" ? "en" : "zh-CN";
}

export function setCurrentLanguage(language: Language): void {
  currentLanguage = language;
  localStorage.setItem("gitkit.language", language);
  document.documentElement.lang = language;
}

export function tx(source: string): string {
  if (currentLanguage !== "en") return source;
  const translated = EN[source] ?? EN[source.replace(/\s+/g, " ")];
  if (translated) return translated;
  const days = /^剩余 (\d+) 天$/.exec(source);
  if (days) return `${days[1]} days remaining`;
  const hours = /^剩余 (\d+) 小时$/.exec(source);
  if (hours) return `${hours[1]} hours remaining`;
  return source;
}

export function tf(pattern: string, ...values: unknown[]): string {
  return tx(pattern).replace(/\{(\d+)\}/g, (match, index: string) => {
    const value = values[Number(index)];
    return value === undefined && Number(index) >= values.length ? match : String(value);
  });
}

export function languageProgress(language: Language): number {
  if (language === "zh-CN") return 100;
  return Math.floor(catalog.filter((source) => !!EN[source]).length / catalog.length * 100);
}
